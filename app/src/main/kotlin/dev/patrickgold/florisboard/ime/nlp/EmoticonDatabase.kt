    // Flat list of all emoticons for fallback or general browsing
    val allEmoticons: List<String> by lazy {
        categories.flatMap { it.emoticons }.distinct()
    }

    fun search(query: String): List<String> {
        if (query.isBlank()) {
            // Return top popular mix
            return allEmoticons.take(50)
        }
        val cleanQuery = query.trim().lowercase()
        val matchedCategories = categories.filter { cat ->
            cat.name.lowercase().contains(cleanQuery) ||
            cat.keywords.any { kw -> 
                cleanQuery.contains(kw.lowercase()) || kw.lowercase().contains(cleanQuery) 
            }
        }
        
        if (matchedCategories.isNotEmpty()) {
            return matchedCategories.flatMap { it.emoticons }.distinct()
        }
        
        // Fallback: search in emoticon strings directly or return generic defaults
        val directMatches = allEmoticons.filter { it.contains(query, ignoreCase = true) }
        if (directMatches.isNotEmpty()) {
            return directMatches
        }

        // Return a generous default list of aesthetic and popular emoticons
        return allEmoticons.take(30)
    }
